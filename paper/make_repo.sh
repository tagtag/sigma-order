#!/bin/sh
#=====================================================================
# Assemble a clean public repository from the working tree.
#
# The working tree carries things that should not be published: versioned
# tarballs, LaTeX build artefacts, __pycache__, the cloned corpora, and the
# local PDF.  This copies only what belongs in a repository, adds the
# public README, a license and a .gitignore, and checks that the self-tests
# still pass from the copy -- a repository whose own tests fail is worse than
# no repository.
#
#   sh make_repo.sh              assemble into ../sigma-order
#   REPO=/path sh make_repo.sh   assemble elsewhere
#   NAME=other-name sh make_repo.sh   assemble into ../other-name
#
# The directory name is also what `gh repo create --source=.` will name the
# repository on GitHub, so it is not a scratch name: pick it here.
#=====================================================================

set -e
cd "$(dirname "$0")"
SRC=".."
: "${NAME:=sigma-order}"
: "${REPO:=../$NAME}"

echo "=== 1. collect ==="
rm -rf "$REPO"
mkdir -p "$REPO/order-intervention" "$REPO/bert-affinity" "$REPO/paper"

# scripts, notes and measured JSON; nothing generated by a build
for d in order-intervention bert-affinity; do
    find "$SRC/$d" -maxdepth 1 -type f \
         \( -name '*.py' -o -name '*.sh' -o -name '*.md' -o -name '*.log' \
            -o -name '*.json' \) -exec cp {} "$REPO/$d/" \;
    # measured results keep their directory structure
    for r in "$SRC/$d"/results_*; do
        [ -d "$r" ] || continue
        mkdir -p "$REPO/$d/$(basename "$r")"
        cp "$r"/*.json "$REPO/$d/$(basename "$r")/" 2>/dev/null || true
    done
done

cp "$SRC/paper/main.tex" "$SRC/paper"/*.py "$SRC/paper"/*.sh "$REPO/paper/"
mkdir -p "$REPO/paper/tables" "$REPO/paper/figures"
cp "$SRC/paper/tables"/*.tex "$REPO/paper/tables/" 2>/dev/null || true
cp "$SRC/paper/figures"/*.pdf "$REPO/paper/figures/" 2>/dev/null || true

# the public README is written for readers, not as a working log; the working
# log stays as order-intervention/README.md
if [ -f "$SRC/REPO_README.md" ]; then
    cp "$SRC/REPO_README.md" "$REPO/README.md"
else
    echo "  WARN: REPO_README.md not found; no top-level README written"
fi

cat > "$REPO/.gitignore" <<'EOF'
__pycache__/
*.pyc
# LaTeX build artefacts; the PDF is rebuilt by paper/build_paper.sh
*.aux
*.fdb_latexmk
*.fls
*.log
*.out
*.synctex.gz
paper/main.pdf
paper/build.log
paper/arxiv_submission/
paper/arxiv_submission.tar.gz
# screen copies of the figures; the PDFs are the ones the paper uses
paper/figures/*.png
# fetched, not ours
Paper2026/
hf/
*.tar.gz
EOF

cat > "$REPO/LICENSE" <<'EOF'
MIT License

Copyright (c) 2026 Y.-H. Taguchi

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
EOF

echo "  $(find "$REPO" -type f | wc -l) files, $(du -sh "$REPO" | cut -f1)"

echo
echo "=== 2. nothing that should not be published ==="
bad=0
for pat in '*.tar.gz' '__pycache__' 'main.pdf' '*.aux'; do
    hits=$(find "$REPO" -name "$pat" | head -5)
    if [ -n "$hits" ]; then
        echo "  PRESENT: $pat"; echo "$hits" | sed 's/^/    /'; bad=1
    fi
done
[ "$bad" = 0 ] && echo "  clean"

echo
echo "=== 3. the self-tests still pass from the copy ==="
ok=1
for t in order-intervention/block_order_selftest.py \
         order-intervention/pll_selftest.py \
         order-intervention/aoar_selftest.py; do
    [ -f "$REPO/$t" ] || continue
    if ( cd "$REPO/$(dirname "$t")" && python3 -I "$(basename "$t")" >/dev/null 2>&1 ); then
        echo "  pass  $t"
    else
        echo "  FAIL  $t"; ok=0
    fi
done
[ "$ok" = 1 ] || { echo "  a self-test fails from the copy -- do not publish yet"; exit 1; }

echo
echo "=== 4. next ==="
cat <<EOF
  cd $REPO
  git init -b main
  git add -A
  git commit -m "Within-text permutation test for fixed-text entropy production"
  gh repo create $NAME --private --source=. --push

Created private.  Two things follow from that:

  * Stay private until arXiv has ANNOUNCED the paper, not merely until it
    is submitted.  Making the repository public earlier would put the work
    in the open with no timestamp on it.  The paper's Reproducibility
    section prints \\repourl as a live link, and that link returning 404
    for a few days is the lesser cost -- arXiv does not check it at
    submission.  Only after the announcement:
        gh repo edit $NAME --visibility public --accept-visibility-change-consequences

  * Set the URL in the paper once the repository exists:
        https://github.com/<your-login>/$NAME

If 'gh' is not installed or not logged in, create the repository in the web
interface instead and push over HTTPS:
  git remote add origin https://github.com/<your-login>/$NAME.git
  git push -u origin main
At the password prompt give a personal access token, not your account
password.  'git config --global credential.helper store' saves it so the
prompt comes only once.
EOF
